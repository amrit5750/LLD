package DesignPatterns.ConcurrencyProblems.BookingSystem.Entity;

import java.time.LocalDateTime;

import DesignPatterns.ConcurrencyProblems.BookingSystem.enums.BookingStatus;
import DesignPatterns.ConcurrencyProblems.BookingSystem.enums.ProductType;

public class Booking {

    private String bookingID;
    private ProductType productType;
    private LocalDateTime bookingTime;
    private LocalDateTime startTime;
    private LocalDateTime endtime;
    private double totalAmount;
    private BookingStatus status;
    private Customer customer;

    public String getBookingID() {
        return bookingID;
    }

    public void setBookingID(String bookingID) {
        this.bookingID = bookingID;
    }

    public ProductType getProductType() {
        return productType;
    }

    public void setProductType(ProductType productType) {
        this.productType = productType;
    }

    public LocalDateTime getBookingTime() {
        return bookingTime;
    }

    public void setBookingTime(LocalDateTime bookingTime) {
        this.bookingTime = bookingTime;
    }

    public LocalDateTime getStartTime() {
        return startTime;
    }

    public void setStartTime(LocalDateTime startTime) {
        this.startTime = startTime;
    }

    public LocalDateTime getEndtime() {
        return endtime;
    }

    public void setEndtime(LocalDateTime endtime) {
        this.endtime = endtime;
    }

    public double getTotalAmount() {
        return totalAmount;
    }

    public void setTotalAmount(double totalAmount) {
        this.totalAmount = totalAmount;
    }

    public BookingStatus getStatus() {
        return status;
    }

    public void setStatus(BookingStatus status) {
        this.status = status;
    }

    public Customer getCustomer() {
        return customer;
    }

    public void setCustomer(Customer customer) {
        this.customer = customer;
    }

}
